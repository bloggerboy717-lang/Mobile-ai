package com.example.util

import android.content.ContentValues
import android.content.Context
import android.os.Build
import android.os.Environment
import android.provider.MediaStore
import android.util.Log
import java.io.File

/**
 * Saves generated live coding scripts and hacker logs directly into
 * the device's public Download folder (Downloads/ALIC_Code/).
 */
object HackerCodeDownloadHelper {
    private const val TAG = "HackerCodeDownload"

    fun saveCodeToDownloads(
        context: Context,
        codeContent: String,
        filePrefix: String = "ALIC_HACKER_CODE"
    ): String? {
        val fileName = "${filePrefix}_${System.currentTimeMillis() / 1000}.kt"
        return try {
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                val contentValues = ContentValues().apply {
                    put(MediaStore.MediaColumns.DISPLAY_NAME, fileName)
                    put(MediaStore.MediaColumns.MIME_TYPE, "text/x-kotlin")
                    put(MediaStore.MediaColumns.RELATIVE_PATH, "${Environment.DIRECTORY_DOWNLOADS}/ALIC_Code")
                }
                val resolver = context.contentResolver
                val uri = resolver.insert(MediaStore.Downloads.EXTERNAL_CONTENT_URI, contentValues)
                if (uri != null) {
                    resolver.openOutputStream(uri)?.use { stream ->
                        stream.write(codeContent.toByteArray(Charsets.UTF_8))
                        stream.flush()
                    }
                    Log.i(TAG, "Saved code script via MediaStore to Downloads/ALIC_Code/$fileName")
                    fileName
                } else {
                    null
                }
            } else {
                val downloadsDir = Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_DOWNLOADS)
                val appDir = File(downloadsDir, "ALIC_Code")
                if (!appDir.exists()) {
                    appDir.mkdirs()
                }
                val targetFile = File(appDir, fileName)
                targetFile.writeText(codeContent, Charsets.UTF_8)
                Log.i(TAG, "Saved code script to legacy Downloads: ${targetFile.absolutePath}")
                fileName
            }
        } catch (e: Exception) {
            Log.e(TAG, "Failed to save code to Downloads", e)
            null
        }
    }

